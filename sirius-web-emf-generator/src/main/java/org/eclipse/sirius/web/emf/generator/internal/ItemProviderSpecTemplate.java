package org.eclipse.sirius.web.emf.generator.internal;

import org.eclipse.emf.codegen.ecore.genmodel.GenClass;

/**
 * Static JET template for the SVG image customization point.
 *
 * @author mcharfadi
 */
public class ItemProviderSpecTemplate {
    // JETEmitter reflects on this field and create(String) to select the line delimiter.
    @SuppressWarnings({ "checkstyle:MemberName", "checkstyle:VisibilityModifier" })
    public final String NL;

    public ItemProviderSpecTemplate() {
        this(System.lineSeparator());
    }

    private ItemProviderSpecTemplate(String lineDelimiter) {
        this.NL = lineDelimiter;
    }

    public static ItemProviderSpecTemplate create(String lineDelimiter) {
        return new ItemProviderSpecTemplate(lineDelimiter);
    }

    public String generate(Object argument) {
        GenClass genClass = (GenClass) argument;
        String providerName = genClass.getProviderClassName();
        String imageOverride = "";
        GenClass imageProvider = genClass;
        while (imageProvider != null && !imageProvider.isImage()) {
            imageProvider = imageProvider.getProviderExtendsGenClass();
        }
        if (imageProvider != null) {
            imageOverride = """

                    @Override
                    public Object getImage(Object object) {
                        return this.overlayImage(object, this.getResourceLocator().getImage("full/obj16/%s.svg"));
                    }
                """.formatted(imageProvider.getName());
        }
        String copyright = genClass.getGenModel().getCopyrightText();
        String header = "";
        if (copyright != null && !copyright.isBlank()) {
            header = "/*\n" + copyright.replace("*/", "* /") + "\n*/\n";
        }
        String result = header + """
                package %s.spec;

                import org.eclipse.emf.common.notify.AdapterFactory;
                import %s;

                /**
                 * Customization of the item provider implementation generated by EMF.
                 */
                public class %sSpec extends %s {
                    public %sSpec(AdapterFactory adapterFactory) {
                        super(adapterFactory);
                    }
                %s
                }
                """.formatted(genClass.getGenPackage().getProviderPackageName(), genClass.getQualifiedProviderClassName(),
                        providerName, providerName, providerName, imageOverride);
        return result.replace("\n", this.NL);
    }
}
